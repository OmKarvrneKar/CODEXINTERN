"""
House Price Prediction

This script loads the California Housing dataset from scikit-learn,
performs exploratory data analysis, preprocesses the data, trains a
Linear Regression model, evaluates it, and visualizes results.

Requirements:
- No manual downloads; dataset fetched via scikit-learn.
- Uses pandas, numpy, matplotlib, seaborn, and scikit-learn.

Author: Generated by assistant
"""

# Imports
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.datasets import fetch_california_housing
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_squared_error, r2_score


def main():
    # -----------------------
    # Data Loading & EDA
    # -----------------------
    # Load California housing dataset (no manual download)
    cal = fetch_california_housing(as_frame=True)

    # Convert to pandas DataFrame with meaningful column names
    df = cal.frame.copy()
    # The target in this dataset is 'MedHouseVal' (median house value)
    # Rename target to 'MedianHouseValue' for clarity
    if 'MedHouseVal' in df.columns:
        df = df.rename(columns={'MedHouseVal': 'MedianHouseValue'})

    print("\n--- Dataset Overview ---\n")
    # First few rows
    print("First 5 rows:\n", df.head(), "\n")

    # Shape
    print("Shape of dataset:", df.shape, "\n")

    # Summary statistics
    print("Summary statistics:\n", df.describe(), "\n")

    # Missing values
    print("Missing values per column:\n", df.isnull().sum(), "\n")

    # -----------------------
    # Visualizations
    # -----------------------
    # Histograms for numerical features
    plt.figure(figsize=(12, 8))
    df.hist(bins=30, figsize=(14, 10), color='steelblue', edgecolor='black')
    plt.suptitle('Feature Distributions', fontsize=16)
    plt.tight_layout(rect=[0, 0.03, 1, 0.95])
    plt.show()

    # Correlation heatmap (features vs target)
    plt.figure(figsize=(10, 8))
    corr = df.corr()
    sns.heatmap(corr, annot=True, fmt='.2f', cmap='coolwarm', square=True)
    plt.title('Correlation Matrix')
    plt.show()

    # -----------------------
    # Data Preprocessing
    # -----------------------
    # Separate features and target
    X = df.drop(columns=['MedianHouseValue'])
    y = df['MedianHouseValue']

    # Train-test split (80% train, 20% test)
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, random_state=42
    )

    # Feature scaling with StandardScaler
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled = scaler.transform(X_test)

    # -----------------------
    # Model Training
    # -----------------------
    model = LinearRegression()
    model.fit(X_train_scaled, y_train)

    # Learned coefficients and intercept
    coef = model.coef_
    intercept = model.intercept_

    print('\n--- Model Coefficients ---\n')
    for feat, c in zip(X.columns, coef):
        print(f"{feat}: {c:.4f}")
    print(f"Intercept: {intercept:.4f}\n")

    # -----------------------
    # Evaluation
    # -----------------------
    # Predict on test set
    y_pred = model.predict(X_test_scaled)

    # Metrics
    mse = mean_squared_error(y_test, y_pred)
    rmse = np.sqrt(mse)
    r2 = r2_score(y_test, y_pred)

    print('--- Evaluation Metrics (Test Set) ---')
    print(f"Mean Squared Error (MSE): {mse:.4f}")
    print(f"Root Mean Squared Error (RMSE): {rmse:.4f}")
    print(f"R-squared (R2 ): {r2:.4f}\n")

    # -----------------------
    # Visualization: Actual vs Predicted
    # -----------------------
    plt.figure(figsize=(8, 6))
    sns.scatterplot(x=y_test, y=y_pred, alpha=0.6)
    # Plot ideal y=x line
    min_val = min(y_test.min(), y_pred.min())
    max_val = max(y_test.max(), y_pred.max())
    plt.plot([min_val, max_val], [min_val, max_val], 'r--', linewidth=2)
    plt.xlabel('Actual Median House Value')
    plt.ylabel('Predicted Median House Value')
    plt.title('Actual vs Predicted Median House Value')
    plt.tight_layout()
    plt.show()


if __name__ == '__main__':
    main()
